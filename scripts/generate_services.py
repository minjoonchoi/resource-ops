#!/usr/bin/env python3
"""Generate services/<name>.yaml from openapi/<organization>/<name>.json."""
import argparse
import json
import sys
from pathlib import Path

import yaml

from catalog_common import CatalogError, NAME, require
from openapi_catalog import make_service

HEADER = '# Generated by scripts/generate_services.py; edit the OpenAPI JSON and regenerate.\n'
MANIFEST = 'catalog/manifest.yaml'


def safe_path(root, relative):
    path = root / relative
    require(path.resolve().is_relative_to(root.resolve()), f'{relative}: path escapes repository')
    require(not any(p.is_symlink() for p in [path, *path.parents] if p != root.parent),
            f'{relative}: symlinks are not supported')
    return path


def files(root, directory):
    base = safe_path(root, directory)
    result = []
    for path in sorted(base.rglob('*')):
        safe_path(root, path.relative_to(root).as_posix())
        if path.is_file():
            result.append(path)
    return result


def unique_object(pairs):
    result = {}
    for key, value in pairs:
        require(key not in result, f'duplicate JSON key {key!r}')
        result[key] = value
    return result


def read_json(root, relative):
    path = safe_path(root, relative)
    require(path.stat().st_size <= 16_777_216, f'{relative}: OpenAPI exceeds 16 MiB')
    text = path.read_text(encoding='utf-8')
    require('${' not in text, f'{relative}: Spring placeholders are forbidden in Config Server data')
    try:
        value = json.loads(text, object_pairs_hook=unique_object,
                           parse_constant=lambda token: (_ for _ in ()).throw(CatalogError(f'non-finite JSON: {token}')))
        require("${" not in json.dumps(value, ensure_ascii=False, allow_nan=False),
                f"{relative}: Spring placeholders are forbidden in Config Server data")
        return value
    except (ValueError, RecursionError) as exc:
        raise CatalogError(f'{relative}: {exc}') from exc


def render(value):
    return HEADER + yaml.safe_dump(value, allow_unicode=True, sort_keys=True, width=100)


def source_index(root):
    entries = {}
    for path in files(root, 'openapi'):
        relative = path.relative_to(root)
        if path.suffix == '.json':
            require(len(relative.parts) == 3, f'{relative}: expected openapi/<organization>/<service>.json')
            entries[relative.as_posix()] = (relative.parts[1], path.stem)
    return entries


def target_source(target):
    parts = target.split('/')
    require(len(parts) == 2 and parts[0] not in ('', '.', '..') and '\\' not in target
            and NAME.fullmatch(parts[1]) and not parts[1].endswith('.json'),
            'target must be <organization>/<service> without .json, e.g. member-team/member-api')
    return f'openapi/{target}.json'


def expected_outputs(root, target=None):
    entries = source_index(root)
    selected = target_source(target) if target is not None else None
    if selected:
        safe_path(root, selected)
        require(selected in entries, f'{selected}: source file does not exist')
    outputs = {}
    for relative, (organization, name) in entries.items():
        if selected and relative != selected:
            continue
        output = f'services/{name}.yaml'
        require(sum(other_name == name for _, other_name in entries.values()) == 1,
                f'duplicate service filename across organizations: {name}')
        outputs[output] = render(make_service(read_json(root, relative), organization, name, relative))
    require(outputs, 'at least one OpenAPI service is required; an empty source tree is not a delete-all request')
    handwritten = []
    for directory in ('actions', 'pages'):
        for path in files(root, directory):
            if path.suffix in ('.yaml', '.yml'):
                relative = path.relative_to(root).as_posix()
                require(path.suffix == '.yaml' and len(path.relative_to(root).parts) == 2,
                        f'{relative}: expected {directory}/<metadata.name>.yaml')
                handwritten.append(relative)
    # A selected conversion must not register other unconverted JSON files or remove other YAMLs.
    service_paths = set(outputs)
    if selected:
        service_paths.update(p.relative_to(root).as_posix() for p in files(root, 'services')
                             if p.suffix in ('.yaml', '.yml'))
    manifest = {'resources': sorted([*service_paths, *handwritten])}
    outputs[MANIFEST] = render(manifest)
    return outputs


def generate(root, mode='write', target=None):
    root = root.resolve()
    outputs = expected_outputs(root, target)
    actual = {p.relative_to(root).as_posix() for p in files(root, 'services') if p.suffix in ('.yaml', '.yml')}
    stale = actual - set(outputs) if target is None else set()
    missing, changed = [], []
    for relative, content in outputs.items():
        path = safe_path(root, relative)
        if not path.exists():
            missing.append(relative)
        elif path.read_bytes() != content.encode('utf-8'):
            changed.append(relative)
    # Never overwrite an existing service in CI, even when the JSON was deliberately changed.
    # The manifest is an inventory of files, updated for new/deleted handwritten definitions.
    mismatched = changed if mode == 'check' else [p for p in changed if p != MANIFEST]
    if mode != 'write':
        require(not stale and not mismatched and (mode != 'check' or not missing),
                f'generated files differ: changed={mismatched}, missing={missing if mode == "check" else []}, '
                f'orphaned={sorted(stale)}; run: python scripts/generate_services.py '
                f'{target or "<organization>/<service> (or --all for a full refresh)"}')
    for relative in sorted(stale):
        require(safe_path(root, relative).read_text(encoding='utf-8').startswith(HEADER),
                f'{relative}: refusing to delete a file not owned by the generator')
    # All validation and comparisons finish before any writes/deletes.
    written = []
    if mode != 'check':
        for relative in [*missing, *changed]:
            path = safe_path(root, relative)
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(outputs[relative], encoding='utf-8')
            written.append(relative)
        for relative in sorted(stale):
            safe_path(root, relative).unlink()
            written.append(relative)
    return written


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('target', nargs='?', help='<organization>/<service>, e.g. member-team/member-api')
    parser.add_argument('--all', action='store_true', help='explicitly process all services (CI/maintenance)')
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[1])
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument('--check', action='store_true', help='compare every output without writes')
    modes.add_argument('--create-missing', action='store_true', help='CI: create missing services, compare existing ones, refresh manifest')
    args = parser.parse_args()
    if bool(args.target) == args.all:
        parser.error('provide exactly one <organization>/<service> target or --all')
    mode = 'check' if args.check else 'create-missing' if args.create_missing else 'write'
    try:
        changed = generate(args.root, mode, args.target)
        print('Generated services verified' if mode == 'check' else f'Generated files updated: {len(changed)}')
        for path in changed:
            print(path)
        return 0
    except (CatalogError, OSError, ValueError, RecursionError) as exc:
        print(f'Service generation failed: {exc}', file=sys.stderr)
        return 1


if __name__ == '__main__':
    sys.exit(main())
